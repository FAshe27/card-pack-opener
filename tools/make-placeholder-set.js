#!/usr/bin/env node
/* Regenerates sets/placeholder.js (250 numbered placeholder cards).
   Usage: node tools/make-placeholder-set.js */
const fs = require('fs');
const path = require('path');

const plan = [ // rarity, how many
  ['common', 120], ['uncommon', 70], ['rare', 35], ['epic', 15], ['legendary', 6], ['chase', 4]
];
const label = { common: 'Common', uncommon: 'Uncommon', rare: 'Rare', epic: 'Epic', legendary: 'Legendary', chase: 'Chase' };
const details = [
  n => `Placeholder details for Card ${n}. Stats, fun facts, or flavor text go here.`,
  n => `Details box: anything goes. A stat line, a quick bio, a fun fact, or a one-liner.`,
  n => `Sample text for Card ${n}. When the real set arrives, this box can hold a stat line, a fun fact, a short story, or nothing at all.`,
  n => `Details TBD.`,
  n => `Example stat line: 12.3 · 45 · 6.78 | Example fun fact: this card is a placeholder.`,
  n => `"Flavor text goes here, in quotes, like a little story." (placeholder)`,
];
const total = plan.reduce((a, [, n]) => a + n, 0);
const cards = [];
let num = 1;
for (const [rarity, count] of plan) {
  for (let i = 0; i < count; i++, num++) {
    const n = String(num).padStart(3, '0');
    let d = details[(num * 7) % details.length](n);
    if (rarity === 'chase') d = `Chase card. One of the rarest pulls in the set (about 1 in 2,000 packs for this exact card). Real details coming soon.`;
    if (rarity === 'legendary') d = `Legendary placeholder. Real details coming soon: stats, a fun fact, or flavor text.`;
    cards.push({ id: n, name: `Card ${n}`, rarity, subtitle: 'Placeholder', details: d });
  }
}
const set = {
  id: 'placeholder',
  name: 'Placeholder Series 1',
  code: 'PH1',
  description: 'Numbered stand-in cards until the real sets are ready.',
  theme: { primary: '#6d5dfc', secondary: '#12c2e9' },
  pack: {
    name: 'Booster Pack',
    slots: [
      { count: 5, label: 'Common', odds: { common: 100 } },
      { count: 2, label: 'Uncommon', odds: { uncommon: 100 } },
      { count: 1, label: 'Wild card', odds: { common: 55, uncommon: 30, rare: 12, epic: 3 } },
      { count: 1, label: 'Rare or better (guaranteed)', odds: { rare: 81.8, epic: 14, legendary: 4, chase: 0.2 } }
    ],
    holo: { common: 2, uncommon: 3, rare: 6, epic: 10, legendary: 15, chase: 25 }
  },
  cards
};
const out = `/* ${set.name}: ${total} placeholder cards. Generated by tools/make-placeholder-set.js. */\n` +
  `CardSets.register(${JSON.stringify(set, null, 2)});\n`;
fs.writeFileSync(path.join(__dirname, '..', 'sets', 'placeholder.js'), out);
console.log(`Wrote sets/placeholder.js (${total} cards)`);
