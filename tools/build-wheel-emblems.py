#!/usr/bin/env python3
"""build-wheel-emblems.py - regenerate the Prize Wheel's baked emblem sprite.

Why: the wheel paints set emblems as pre-rendered images instead of live
canvas fillText, because platform emoji fonts (iOS especially) draw glyphs
small, padded and inconsistent. This script collects every set's emblem from
sets/boot-index.js, downloads the matching Noto Color Emoji PNG (128px,
pinned noto-emoji tag below), composites them into
assets/wheel-emblems.png, and writes the emblem -> cell map to
js/wheel-emblems.js. Run it whenever a set is added or an emblem changes,
then commit all three files (this tool's outputs + the sprite) together.

Requires: Python 3 + Pillow (pip install pillow). Network access to
cdn.jsdelivr.net (GitHub mirror of googlefonts/noto-emoji).
"""
import io
import json
import os
import sys
import tempfile
import urllib.request

from PIL import Image

NOTO_TAG = "v2.042"
NOTO_URL = "https://cdn.jsdelivr.net/gh/googlefonts/noto-emoji@%s/png/128/emoji_u%s.png"
CELL, COLS = 128, 8
FALLBACK = "\U0001F381"  # gift - wheel.js's fallback emblem

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def glyph_name(emblem):
    cps = "_".join("%04x" % ord(c) for c in emblem if ord(c) != 0xFE0F)
    return "emoji_u" + cps


def main():
    with open(os.path.join(ROOT, "sets", "boot-index.js")) as f:
        raw = f.read()
    index = json.loads(raw[raw.index("{"):raw.rindex("}") + 1])
    emblems = {m["emblem"] for m in index["sets"].values() if m.get("emblem")}
    emblems.add(FALLBACK)
    ordered = sorted(emblems, key=lambda e: [ord(c) for c in e if ord(c) != 0xFE0F])
    print("%d emblems" % len(ordered))

    rows = (len(ordered) + COLS - 1) // COLS
    sprite = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    with tempfile.TemporaryDirectory() as tmp:
        for i, emblem in enumerate(ordered):
            name = glyph_name(emblem)
            path = os.path.join(tmp, name + ".png")
            urllib.request.urlretrieve(NOTO_URL % (NOTO_TAG, name[7:]), path)
            glyph = Image.open(path)
            if glyph.size != (CELL, CELL):
                raise SystemExit("%s: unexpected size %s" % (name, glyph.size))
            sprite.paste(glyph, ((i % COLS) * CELL, (i // COLS) * CELL))

    out_png = os.path.join(ROOT, "assets", "wheel-emblems.png")
    sprite.save(out_png, optimize=True)
    print("wrote %s (%d bytes)" % (out_png, os.path.getsize(out_png)))

    buf = io.StringIO()
    buf.write("/* GENERATED by tools/build-wheel-emblems.py - do not hand-edit.\n")
    buf.write("   Emblem -> sprite cell map for the Prize Wheel. Regenerate (with\n")
    buf.write("   assets/wheel-emblems.png) whenever a set emblem changes. */\n")
    buf.write("window.WHEEL_EMBLEMS = { cols: %d, cell: %d, map: {" % (COLS, CELL))
    buf.write(", ".join(json.dumps(e, ensure_ascii=False) + ": " + str(i)
                          for i, e in enumerate(ordered)))
    buf.write("} };\n")
    out_js = os.path.join(ROOT, "js", "wheel-emblems.js")
    with open(out_js, "w") as f:
        f.write(buf.getvalue())
    print("wrote %s" % out_js)


if __name__ == "__main__":
    sys.exit(main())
