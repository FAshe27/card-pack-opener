#!/usr/bin/env node
/* Builds supabase/setup.sql = all migrations + every set in sets/manifest.js.
   Paste that file into Supabase Dashboard -> SQL Editor -> Run (safe to re-run).
   Usage: node tools/build-setup-sql.js */
const fs = require('fs');
const path = require('path');
const { loadAll, seedSql, ROOT } = require('./lib/sets');

const migDir = path.join(ROOT, 'supabase', 'migrations');
const migs = fs.readdirSync(migDir).filter(f => f.endsWith('.sql')).sort();
const sets = loadAll().all().filter(s => s.source !== 'imported');
let out = `-- =====================================================================
-- YayPelleds (card pack opener): full database setup. GENERATED by tools/build-setup-sql.js
-- Paste into Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Safe to run again (e.g. after adding a set). Does NOT create the admin
-- account: run the one-line bootstrap shown in the README afterwards.
-- =====================================================================\n\n`;
for (const m of migs) out += `-- ---- migration ${m}\n` + fs.readFileSync(path.join(migDir, m), 'utf8') + '\n';
out += '\n-- ---- sets\n';
for (const s of sets) out += seedSql(s) + '\n';
out += "notify pgrst, 'reload schema';\n";
fs.writeFileSync(path.join(ROOT, 'supabase', 'setup.sql'), out);
console.log(`Wrote supabase/setup.sql (${migs.length} migration(s), ${sets.length} set(s): ${sets.map(s => s.id).join(', ')}, ${(out.length / 1024).toFixed(0)} KB)`);
